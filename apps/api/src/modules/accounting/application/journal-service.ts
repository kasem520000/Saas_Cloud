import { Inject, Injectable } from "@nestjs/common";

import { AuditService } from "../../audit/api/audit";
import { ownTenantBaseCurrency } from "../../../infra/settings/setting-reader";
import * as store from "../infrastructure/accounting.store";
import * as journal from "../infrastructure/journal.store";
import {
  ApprovalsPendingError,
  ApprovalLimitExceededError,
  ApprovalPolicyInvalidError,
  JournalDraftNotFoundError,
  JournalStateError,
  JournalUnbalancedError,
  RecurringJournalNotFoundError,
  RecurringTemplateInvalidError,
  SelfApprovalBlockedError,
} from "../domain/accounting-errors";
import { PostingService } from "./posting-service";
import { addExact, compareExact, multiplyExact } from "./decimal-strings";
import type { JournalSpec, JournalLineSpec } from "../domain/posting-engine/journal-spec";

/**
 * Manual journals service (PHASE-007 T9/T10/T11; JOURNAL_RULES §1–§3):
 * draft → submit → approve → post lifecycle, bilingual memos, drafts
 * editable/deletable before posting (audit-logged), journal templates
 * (documents, not postings), recurring definitions generating DRAFTs only,
 * and the BR-034 approval policies (SoD default OFF, thresholds in BASE
 * currency, preview generated by the same engine code that posts).
 */

export interface DraftLineInput {
  accountId: string;
  direction: "DEBIT" | "CREDIT";
  amount: string;
  partnerId?: string | null;
  itemId?: string | null;
  costCenterId?: string | null;
  taxCodeId?: string | null;
  memo?: string | null;
  memoAr?: string | null;
}

export interface CreateDraftInput {
  entryDate: string;
  currencyCode?: string;
  exchangeRate?: string | null;
  rateSource?: "TABLE" | "MANUAL";
  description?: string | null;
  descriptionAr?: string | null;
  reference?: string | null;
  lines: DraftLineInput[];
  templateId?: string | null;
  recurrenceId?: string | null;
}

const APPROVAL_MODES = ["none", "single-approver", "two-step", "amount-threshold"] as const;
type ApprovalMode = (typeof APPROVAL_MODES)[number];

interface ApprovalPolicyShape {
  mode: ApprovalMode;
  threshold?: string | null;
  allowSelfApproval?: boolean;
}

@Injectable()
export class JournalService {
  constructor(
    @Inject(AuditService) private readonly audit: AuditService,
    private readonly posting: PostingService,
  ) {}

  // -- drafts -----------------------------------------------------------------

  async list(filter: { status?: string; recurrenceId?: string; limit?: number } = {}) {
    return journal.listManualJournals({ ...filter, limit: filter.limit ?? 50 });
  }

  async get(id: string): Promise<{ draft: journal.ManualJournalRow; lines: journal.ManualJournalLine[] }> {
    const draft = await this.requireDraft(id);
    return { draft, lines: await journal.listManualJournalLines(id) };
  }

  async create(actorId: string, input: CreateDraftInput): Promise<journal.ManualJournalRow> {
    const base = await ownTenantBaseCurrency();
    const currency = input.currencyCode ?? base;
    let exchangeRate = input.exchangeRate ?? null;
    if (currency !== base) {
      if (exchangeRate === null) {
        // Dated table lookup (JOURNAL_RULES §4.1) — manual override recorded
        // when the user sets it; absence surfaces at posting (MISSING_FX_RATE).
        const rateRow = await (await import("../infrastructure/accounting.store")).findRateForDate(
          currency,
          input.entryDate,
        );
        exchangeRate = rateRow?.rate ?? null;
      }
    } else {
      exchangeRate = "1";
    }
    const draft = await journal.insertManualJournal({
      createdBy: actorId,
      entryDate: input.entryDate,
      currencyCode: currency,
      exchangeRate,
      rateSource: input.rateSource ?? (exchangeRate !== null && exchangeRate !== "1" ? "TABLE" : "TABLE"),
      description: input.description ?? null,
      descriptionAr: input.descriptionAr ?? null,
      reference: input.reference ?? null,
      recurrenceId: input.recurrenceId ?? null,
      templateId: input.templateId ?? null,
    });
    await journal.replaceManualJournalLines(draft.id, input.lines.map((line, index) => ({
      lineNo: index + 1,
      accountId: line.accountId,
      direction: line.direction,
      amount: line.amount,
      partnerId: line.partnerId ?? null,
      itemId: line.itemId ?? null,
      costCenterId: line.costCenterId ?? null,
      taxCodeId: line.taxCodeId ?? null,
      memo: line.memo ?? null,
      memoAr: line.memoAr ?? null,
    })));
    await this.audit.record({
      action: "accounting.journal_draft_created",
      entityType: "manual_journal",
      entityId: draft.id,
      actorId,
      after: { entryDate: draft.entryDate, currency: draft.currencyCode, lines: input.lines.length },
    });
    return draft;
  }

  async update(
    actorId: string,
    id: string,
    patch: {
      entryDate?: string;
      exchangeRate?: string | null;
      description?: string | null;
      descriptionAr?: string | null;
      reference?: string | null;
      lines?: DraftLineInput[];
    },
  ): Promise<journal.ManualJournalRow> {
    const before = await this.requireDraft(id);
    if (before.status !== "DRAFT") {
      throw new JournalStateError(`draft is ${before.status} — only DRAFT journals are editable`);
    }
    const updated = await journal.updateManualJournal(id, patch);
    if (patch.lines !== undefined) {
      await journal.replaceManualJournalLines(id, patch.lines.map((line, index) => ({
        lineNo: index + 1,
        accountId: line.accountId,
        direction: line.direction,
        amount: line.amount,
        partnerId: line.partnerId ?? null,
        itemId: line.itemId ?? null,
        costCenterId: line.costCenterId ?? null,
        taxCodeId: line.taxCodeId ?? null,
        memo: line.memo ?? null,
        memoAr: line.memoAr ?? null,
      })));
    }
    await this.audit.record({
      action: "accounting.journal_draft_updated",
      entityType: "manual_journal",
      entityId: id,
      actorId,
      before: { entryDate: before.entryDate },
      after: { entryDate: updated?.entryDate, lines: patch.lines?.length },
    });
    return updated!;
  }

  /** Draft deletion (JOURNAL_RULES §1.2) — pre-POST only, audit-logged. */
  async remove(actorId: string, id: string): Promise<void> {
    const draft = await this.requireDraft(id);
    if (draft.status !== "DRAFT") {
      throw new JournalStateError(`draft is ${draft.status} — only DRAFT journals are deletable`);
    }
    await journal.deleteManualJournal(id);
    await this.audit.record({
      action: "accounting.journal_draft_deleted",
      entityType: "manual_journal",
      entityId: id,
      actorId,
      before: { entryDate: draft.entryDate, currency: draft.currencyCode },
    });
  }

  // -- lifecycle ----------------------------------------------------------------

  /**
   * Submit (DRAFT → PENDING_APPROVAL or APPROVED under a `none` policy).
   * Requires balanced lines (JOURNAL_RULES §1.4) in document + base terms.
   */
  async submit(actorId: string, id: string): Promise<journal.ManualJournalRow> {
    const draft = await this.requireDraft(id);
    if (draft.status !== "DRAFT") {
      throw new JournalStateError(`draft is ${draft.status} — submit requires DRAFT`);
    }
    await this.assertBalanced(id);
    const policy = await this.policyFor("journal_entry", draft.entryDate);
    if (policy.mode === "none") {
      const updated = await journal.setManualJournalState(id, { status: "APPROVED", approvalStep: 0 });
      await this.audit.record({
        action: "accounting.journal_auto_approved",
        entityType: "manual_journal",
        entityId: id,
        actorId,
        after: { policy: "none" },
      });
      return updated!;
    }
    const updated = await journal.setManualJournalState(id, {
      status: "PENDING_APPROVAL",
      submittedBy: actorId,
      approvalStep: 0,
    });
    await this.audit.record({
      action: "accounting.journal_submitted",
      entityType: "manual_journal",
      entityId: id,
      actorId,
      after: { policy: policy.mode },
    });
    return updated!;
  }

  /**
   * Approve (PENDING_APPROVAL → APPROVED). BR-034: SoD — the creator
   * cannot approve unless allow_self_approval (default OFF, server-side);
   * amount-threshold compares the TOTAL BASE-CURRENCY amount (at-limit
   * passes, +0.01 fails APPROVAL_LIMIT_EXCEEDED); two-step needs two
   * DISTINCT approvers.
   */
  async approve(actorId: string, id: string, note?: string): Promise<journal.ManualJournalRow> {
    const draft = await this.requireDraft(id);
    if (draft.status !== "PENDING_APPROVAL") {
      throw new JournalStateError(`draft is ${draft.status} — approve requires PENDING_APPROVAL`);
    }
    const policy = await this.policyFor("journal_entry", draft.entryDate);
    if (draft.createdBy === actorId && policy.allowSelfApproval !== true) {
      throw new SelfApprovalBlockedError();
    }
    if (policy.mode === "amount-threshold" && policy.threshold !== undefined && policy.threshold !== null) {
      const totalBase = await this.totalBaseAmount(id);
      if (compareExact(totalBase, policy.threshold) > 0) {
        throw new ApprovalLimitExceededError({ total: totalBase, limit: policy.threshold });
      }
    }
    const steps = policy.mode === "two-step" ? 2 : 1;
    const received = draft.approvalStep;
    if (received < steps) {
      const nextStep = received + 1;
      if (nextStep >= steps) {
        const updated = await journal.setManualJournalState(id, {
          status: "APPROVED",
          approvalStep: steps,
          approvedBy: actorId,
        });
        await this.audit.record({
          action: "accounting.journal_approved",
          entityType: "manual_journal",
          entityId: id,
          actorId,
          after: { step: steps, note: note ?? null },
        });
        return updated!;
      }
      const updated = await journal.setManualJournalState(id, { approvalStep: nextStep });
      await this.audit.record({
        action: "accounting.journal_approval_step",
        entityType: "manual_journal",
        entityId: id,
        actorId,
        after: { step: nextStep, of: steps },
      });
      return updated!;
    }
    throw new JournalStateError("approval already complete");
  }

  /** Cancel (pre-effect; audit-logged with reason). */
  async cancel(actorId: string, id: string, reason: string): Promise<journal.ManualJournalRow> {
    const draft = await this.requireDraft(id);
    if (draft.status === "POSTED" || draft.status === "CANCELLED") {
      throw new JournalStateError(`draft is ${draft.status} — cannot cancel`);
    }
    const updated = await journal.setManualJournalState(id, {
      status: "CANCELLED",
      cancelledBy: actorId,
      cancelReason: reason,
    });
    await this.audit.record({
      action: "accounting.journal_cancelled",
      entityType: "manual_journal",
      entityId: id,
      actorId,
      before: { status: draft.status },
      after: { status: "CANCELLED", reason },
    });
    return updated!;
  }

  /**
   * The approver preview: the EXACT spec the engine will post — built by
   * the same code path as `post()` (BR-034: no preview/post divergence).
   */
  async previewSpec(id: string): Promise<JournalSpec> {
    return this.buildSpec(id);
  }

  /** Post an APPROVED draft through the engine (source `journal_entry`). */
  async post(
    actorId: string,
    id: string,
    options: { softCloseReason?: string } = {},
  ): Promise<{ draft: journal.ManualJournalRow; result: { journalEntryId: string; entryNo: string | null } }> {
    const draft = await this.requireDraft(id);
    if (draft.status === "POSTED" && draft.postedJournalId !== null) {
      // Idempotent re-post surfaces the stored entry (INV-013 replay).
      const entry = await journal.findEntryById(draft.postedJournalId);
      return {
        draft,
        result: { journalEntryId: draft.postedJournalId, entryNo: entry?.entryNo ?? null },
      };
    }
    if (draft.status !== "APPROVED") {
      throw new ApprovalsPendingError();
    }
    const spec = await this.buildSpec(id);
    if (options.softCloseReason !== undefined) {
      spec.softCloseReason = options.softCloseReason;
    }
    const result = await this.posting.post(spec, { postedBy: actorId });
    const updated = await journal.setManualJournalState(id, {
      status: "POSTED",
      postedJournalId: result.journalEntryId,
      postedBy: actorId,
    });
    return { draft: updated!, result };
  }

  /** Reverse the posted entry of a draft (INV-014 through the same engine). */
  async reverse(
    actorId: string,
    id: string,
    input: { entryDate: string; reason: string },
  ) {
    const draft = await this.requireDraft(id);
    if (draft.postedJournalId === null) {
      throw new JournalStateError("journal is not posted — nothing to reverse");
    }
    return this.posting.reverse(
      { originalEntryId: draft.postedJournalId, entryDate: input.entryDate, reason: input.reason },
      { reversedBy: actorId },
    );
  }

  // -- recurring journals (T10) ---------------------------------------------------

  async listRecurring() {
    return store.listRecurringJournals();
  }

  async getRecurring(id: string) {
    const row = await store.findRecurringJournalById(id);
    if (row === undefined) throw new RecurringJournalNotFoundError(id);
    return row;
  }

  async createRecurring(
    actorId: string,
    input: {
      name: string;
      template: { lines: DraftLineInput[]; amountPolicy: "FIXED" | "RE_ENTER" };
      schedule: string;
      startDate: string;
      endDate?: string | null;
      nextRunDate: string;
    },
  ): Promise<store.RecurringJournalRow> {
    if (!input.template.lines || input.template.lines.length < 2) {
      throw new RecurringTemplateInvalidError("template needs >= 2 lines");
    }
    if (!["FIXED", "RE_ENTER"].includes(input.template.amountPolicy)) {
      throw new RecurringTemplateInvalidError("amountPolicy must be FIXED or RE_ENTER");
    }
    const created = await store.insertRecurringJournal({
      name: input.name,
      template: input.template,
      schedule: input.schedule,
      startDate: input.startDate,
      endDate: input.endDate ?? null,
      nextRunDate: input.nextRunDate,
    });
    await this.audit.record({
      action: "accounting.recurring_journal_created",
      entityType: "recurring_journal",
      entityId: created.id,
      actorId,
      after: { name: created.name, schedule: created.schedule },
    });
    return created;
  }

  async setRecurringStatus(actorId: string, id: string, status: "ACTIVE" | "PAUSED") {
    const updated = await store.updateRecurringJournal(id, { status });
    if (updated === undefined) throw new RecurringJournalNotFoundError(id);
    await this.audit.record({
      action: "accounting.recurring_journal_status",
      entityType: "recurring_journal",
      entityId: id,
      actorId,
      after: { status },
    });
    return updated;
  }

  /**
   * The due-generation step (pg-boss job or manual tick): creates DRAFT
   * entries only — NEVER posts (JOURNAL_RULES §2). Skip rules: period
   * locked → notification row (audit), inactive, end passed. Idempotent
   * per run via the recurrence + next_run guard.
   */
  async generateDueRecurring(
    actorId: string | null,
    asOf: string,
  ): Promise<{ generated: string[]; skipped: { id: string; reason: string }[] }> {
    const due = await store.findDueRecurringJournals(asOf);
    const generated: string[] = [];
    const skipped: { id: string; reason: string }[] = [];
    for (const definition of due) {
      const period = await store.findPeriodForDate(definition.nextRunDate);
      if (period === undefined || period.status === "LOCKED") {
        skipped.push({ id: definition.id, reason: "period locked or missing" });
        await this.audit.record({
          action: "accounting.recurring_skipped",
          entityType: "recurring_journal",
          entityId: definition.id,
          actorId: actorId ?? undefined,
          after: { nextRunDate: definition.nextRunDate, reason: "period locked" },
        });
        continue;
      }
      const template = definition.template as { lines?: DraftLineInput[]; amountPolicy?: string };
      if (template?.lines === undefined || template.lines.length < 2) {
        skipped.push({ id: definition.id, reason: "template invalid" });
        continue;
      }
      const draft = await this.create(actorId ?? "", {
        entryDate: definition.nextRunDate,
        description: `Recurring: ${definition.name}`,
        descriptionAr: `قيود دورية: ${definition.name}`,
        lines: template.lines,
        recurrenceId: definition.id,
      });
      generated.push(draft.id);
      await store.updateRecurringJournal(definition.id, {
        lastRunAt: new Date().toISOString(),
        nextRunDate: advanceSchedule(definition.schedule, definition.nextRunDate),
      });
      await this.audit.record({
        action: "accounting.recurring_generated",
        entityType: "manual_journal",
        entityId: draft.id,
        actorId: actorId ?? undefined,
        after: { recurrenceId: definition.id, entryDate: definition.nextRunDate },
      });
    }
    return { generated, skipped };
  }

  // -- approval policies (T11) ------------------------------------------------------

  async listPolicies() {
    return store.listApprovalPolicies();
  }

  async upsertPolicy(
    actorId: string,
    input: {
      docType: string;
      mode: string;
      threshold?: string | null;
      allowSelfApproval?: boolean;
      appliesFrom: string;
    },
  ): Promise<store.ApprovalPolicyRow> {
    if (!APPROVAL_MODES.includes(input.mode as ApprovalMode)) {
      throw new ApprovalPolicyInvalidError(
        `mode must be one of ${APPROVAL_MODES.join("|")} (got ${input.mode})`,
      );
    }
    if (input.mode === "amount-threshold" && (input.threshold === undefined || input.threshold === null)) {
      throw new ApprovalPolicyInvalidError("amount-threshold mode requires a threshold (base currency)");
    }
    if (input.allowSelfApproval === true) {
      throw new ApprovalPolicyInvalidError(
        "allow_self_approval cannot be enabled at policy creation (BR-034 SoD default OFF — requires an explicit tenant decision record)",
      );
    }
    const created = await store.insertApprovalPolicy({
      docType: input.docType,
      policy: {
        mode: input.mode,
        threshold: input.threshold ?? null,
        allowSelfApproval: false,
      },
      appliesFrom: input.appliesFrom,
    });
    await this.audit.record({
      action: "accounting.approval_policy_created",
      entityType: "approval_policy",
      entityId: created.id,
      actorId,
      after: { docType: input.docType, policy: created.policy },
    });
    return created;
  }

  // -- internals ----------------------------------------------------------------------

  private async requireDraft(id: string): Promise<journal.ManualJournalRow> {
    const draft = await journal.findManualJournalById(id);
    if (draft === undefined) throw new JournalDraftNotFoundError(id);
    return draft;
  }

  private async policyFor(docType: string, onDate: string): Promise<ApprovalPolicyShape> {
    const policy = await store.findActivePolicy(docType, onDate);
    if (policy === undefined) {
      return { mode: "none", allowSelfApproval: false };
    }
    return policy.policy as ApprovalPolicyShape;
  }

  /** Balanced in document AND base terms (JOURNAL_RULES §1.4). */
  private async assertBalanced(id: string): Promise<void> {
    const lines = await journal.listManualJournalLines(id);
    if (lines.length < 2) throw new JournalUnbalancedError();
    let debit = "0";
    let credit = "0";
    for (const line of lines) {
      if (line.direction === "DEBIT") {
        debit = addExact(debit, line.amount);
      } else {
        credit = addExact(credit, line.amount);
      }
    }
    if (debit !== credit) throw new JournalUnbalancedError();
  }

  private async totalBaseAmount(id: string): Promise<string> {
    const draft = await this.requireDraft(id);
    const lines = await journal.listManualJournalLines(id);
    let total = "0";
    for (const line of lines) {
      total = addExact(total, multiplyExact(line.amount, draft.exchangeRate ?? "1"));
    }
    return total;
  }

  /** The single spec builder — preview AND post use it (no divergence). */
  private async buildSpec(id: string): Promise<JournalSpec> {
    const draft = await this.requireDraft(id);
    const lines = await journal.listManualJournalLines(id);
    const specLines: JournalLineSpec[] = lines.map((line) => ({
      accountId: line.accountId,
      direction: line.direction === "DEBIT" ? "DEBIT" : "CREDIT",
      amount: line.amount,
      partnerId: line.partnerId ?? undefined,
      itemId: line.itemId ?? undefined,
      costCenterId: line.costCenterId ?? undefined,
      taxCodeId: line.taxCodeId ?? undefined,
      memo: { en: line.memo ?? undefined, ar: line.memoAr ?? undefined },
    }));
    return {
      source: { docType: "journal_entry", docId: draft.id, operation: "post" },
      entryDate: draft.entryDate,
      description: { en: draft.description ?? undefined, ar: draft.descriptionAr ?? undefined },
      reference: draft.reference ?? undefined,
      currency: draft.currencyCode,
      exchangeRate: draft.exchangeRate ?? undefined,
      lines: specLines,
    };
  }
}



/** Next run date per schedule (monthly/weekly/daily/quarterly/yearly). */
export function advanceSchedule(schedule: string, from: string): string {
  const date = new Date(`${from}T00:00:00Z`);
  switch (schedule) {
    case "DAILY":
      date.setUTCDate(date.getUTCDate() + 1);
      break;
    case "WEEKLY":
      date.setUTCDate(date.getUTCDate() + 7);
      break;
    case "QUARTERLY":
      date.setUTCMonth(date.getUTCMonth() + 3);
      break;
    case "YEARLY":
      date.setUTCFullYear(date.getUTCFullYear() + 1);
      break;
    case "MONTHLY":
    default:
      date.setUTCMonth(date.getUTCMonth() + 1);
      break;
  }
  return date.toISOString().slice(0, 10);
}
